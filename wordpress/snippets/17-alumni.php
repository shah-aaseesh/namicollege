	'add_meta_boxes_nami_alumni',
	function ( $post ) {
		$submitter = get_post_meta( $post->ID, '_nami_submitter', true );
		if ( ! is_array( $submitter ) || empty( $submitter['name'] ) ) {
			return;
		}
		add_meta_box(
			'nami_alumni_submitter',
			'Submitted by',
			function () use ( $submitter ) {
				$email = (string) ( $submitter['email'] ?? '' );
				printf(
					'<p><strong>%s</strong><br>%s<br>%s<br>%s</p><p class="description">Sent %s through "Share Your Story". Only staff see this box. They agreed to their story being shared.</p>',
					esc_html( (string) $submitter['name'] ),
					'' !== $email ? '<a href="mailto:' . esc_attr( $email ) . '">' . esc_html( $email ) . '</a>' : '',
					esc_html( (string) ( $submitter['phone'] ?? '' ) ),
					'' !== ( $submitter['linkedin'] ?? '' ) ? '<a href="' . esc_url( $submitter['linkedin'] ) . '" target="_blank" rel="noopener">LinkedIn ↗</a>' : '',
					esc_html( (string) ( $submitter['received'] ?? '' ) )
				);
			},
			'nami_alumni',
			'side',
			'high'
		);
	}
);

// Red bubble on the Alumni menu with the number of stories waiting for review.
add_action(
	'admin_menu',
	function () {
		global $menu;
		if ( ! current_user_can( 'edit_pages' ) || ! is_array( $menu ) ) {
			return;
		}
		$waiting = new WP_Query(
			array(
				'post_type'      => 'nami_alumni',
				'post_status'    => 'draft',
				'meta_key'       => '_nami_submitter',
				'fields'         => 'ids',
				'posts_per_page' => 1,
			)
		);
		if ( $waiting->found_posts < 1 ) {
			return;
		}
		foreach ( $menu as $index => $item ) {
			if ( 'edit.php?post_type=nami_alumni' === ( $item[2] ?? '' ) ) {
				$menu[ $index ][0] .= sprintf( ' <span class="awaiting-mod"><span class="pending-count">%d</span></span>', (int) $waiting->found_posts );
			}
		}
	},
	99
);
