add_action(
	'rest_api_init',
	function () {
		register_rest_route(
			'nami/v1',
			'/alumni-submissions',
			array(
				'methods'             => 'POST',
				'permission_callback' => function ( WP_REST_Request $request ) {
					if ( ! function_exists( 'nami_cms_settings' ) ) {
						return new WP_Error( 'nami_alumni_core_missing', 'The NAMI CMS core snippet is not active.', array( 'status' => 503 ) );
					}
					$secret = (string) nami_cms_settings()['secret'];
					return '' !== $secret && hash_equals( $secret, (string) $request->get_header( 'x-nami-secret' ) );
				},
				'callback'            => 'nami_alumni_receive',
			)
		);
	}
);

function nami_alumni_text( $body, $key, $max = 300 ) {
	return mb_substr( sanitize_text_field( (string) ( $body[ $key ] ?? '' ) ), 0, $max );
}

/** Saves the submitted photo in the Media Library; returns the image field value. */
function nami_alumni_save_photo( $photo, $name ) {
	$empty = array( 'src' => '', 'alt' => '', 'width' => 0, 'height' => 0 );
	if ( ! is_array( $photo ) ) {
		return $empty;
	}
	$bytes = base64_decode( (string) ( $photo['data'] ?? '' ), true );
	$info  = false !== $bytes ? getimagesizefromstring( $bytes ) : false;
	$types = array( 'image/jpeg' => 'jpg', 'image/png' => 'png', 'image/webp' => 'webp' );
	if ( false === $info || ! isset( $types[ $info['mime'] ] ) || strlen( $bytes ) > 4194304 ) {
		return $empty;
	}

	$filename = sanitize_file_name( 'alumni-' . sanitize_title( $name ) . '-' . wp_generate_password( 6, false ) . '.' . $types[ $info['mime'] ] );
	$upload   = wp_upload_bits( $filename, null, $bytes );
	if ( ! empty( $upload['error'] ) ) {
		return $empty;
	}
	$attachment = wp_insert_attachment(
		array(
			'post_mime_type' => $info['mime'],
			'post_title'     => $name,
			'post_status'    => 'inherit',
		),
		$upload['file']
	);
	if ( is_wp_error( $attachment ) || ! $attachment ) {
		return $empty;
	}
	require_once ABSPATH . 'wp-admin/includes/image.php';
	wp_update_attachment_metadata( $attachment, wp_generate_attachment_metadata( $attachment, $upload['file'] ) );
	update_post_meta( $attachment, '_wp_attachment_image_alt', $name );

	return array(
		'src'    => $upload['url'],
		'alt'    => $name,
		'width'  => (int) $info[0],
		'height' => (int) $info[1],
	);
}

function nami_alumni_receive( WP_REST_Request $request ) {
	$body = $request->get_json_params();
	$body = is_array( $body ) ? $body : array();
	$name = nami_alumni_text( $body, 'fullName', 200 );
	if ( '' === $name || ! function_exists( 'nami_cms_collections' ) ) {
		return new WP_Error( 'nami_alumni_bad_body', 'Invalid story.', array( 'status' => 400 ) );
	}
	$config = nami_cms_collections()['alumni-stories'] ?? null;
	if ( null === $config ) {
		return new WP_Error( 'nami_alumni_missing', 'The alumni list is not set up.', array( 'status' => 500 ) );
	}

	// The form's wing names → the website's wings.
	$wing_text = nami_alumni_text( $body, 'wing', 100 );
	$wing_map  = array(
		'Undergraduate Program' => 'undergraduate',
		'Graduate Program'      => 'graduate',
		'Cambridge A Levels'    => 'college',
		'Secondary School'      => 'higher-secondary',
		'School'                => 'higher-secondary',
	);
	$role      = nami_alumni_text( $body, 'currentRole' );
	$org       = nami_alumni_text( $body, 'currentOrg' );
	$headline  = nami_alumni_text( $body, 'storyHeadline' );
	$advice    = mb_substr( sanitize_textarea_field( (string) ( $body['advice'] ?? '' ) ), 0, 3000 );
	$story     = mb_substr( sanitize_textarea_field( (string) ( $body['experience'] ?? '' ) ), 0, 10000 );

	$GLOBALS['nami_cms_quiet'] = true; // A draft does not change the website.
	$post_id                   = wp_insert_post(
		array(
			'post_type'   => 'nami_alumni',
			'post_status' => 'draft',
			'post_title'  => $name,
		),
		true
	);
	$GLOBALS['nami_cms_quiet'] = false;
	if ( is_wp_error( $post_id ) ) {
		return new WP_Error( 'nami_alumni_store_failed', 'The story could not be stored.', array( 'status' => 500 ) );
	}

	$fields = nami_cms_collection_clean(
		$config,
		array(
			'wing'           => $wing_map[ $wing_text ] ?? 'undergraduate',
			'photo'          => nami_alumni_save_photo( $body['photo'] ?? null, $name ),
			'programme'      => nami_alumni_text( $body, 'program' ),
			'graduationYear' => nami_alumni_text( $body, 'graduationYear', 60 ),
			'currentRole'    => $role,
			'company'        => $org,
			'location'       => nami_alumni_text( $body, 'location' ),
			'highlights'     => $headline,
			'keyQuote'       => '',
			'story'          => $story,
			'milestones'     => array(),
			'interview'      => '' === $advice ? array() : array(
				array(
					'question' => 'What advice would you give to current and future students?',
					'answer'   => $advice,
				),
			),
			'skills'         => '',
		)
	);
	update_post_meta( $post_id, '_nami_fields', wp_slash( $fields ) );
	update_post_meta(
		$post_id,
		'_nami_submitter',
		wp_slash(
			array(
				'name'     => $name,
				'email'    => sanitize_email( (string) ( $body['email'] ?? '' ) ),
				'phone'    => nami_alumni_text( $body, 'phone', 60 ),
				'linkedin' => esc_url_raw( (string) ( $body['linkedin'] ?? '' ) ),
				'wing'     => $wing_text,
				'headline' => $headline,
				'received' => current_time( 'mysql' ),
			)
		)
	);

	nami_alumni_notify( $post_id );
	return rest_ensure_response( array( 'ok' => true ) );
}

function nami_alumni_notify( $post_id ) {
	$values = function_exists( 'nami_cms_get_values' ) ? nami_cms_get_values( 'alumni' ) : array();
	$to     = sanitize_email( (string) ( $values['connect']['email'] ?? '' ) );
	if ( ! is_email( $to ) ) {
		return;
	}
	$submitter = get_post_meta( $post_id, '_nami_submitter', true );
	$submitter = is_array( $submitter ) ? $submitter : array();
	$fields    = get_post_meta( $post_id, '_nami_fields', true );
	$fields    = is_array( $fields ) ? $fields : array();
	$headers   = array( 'Content-Type: text/html; charset=UTF-8' );
	if ( is_email( $submitter['email'] ?? '' ) ) {
		$headers[] = 'Reply-To: ' . str_replace( array( "\r", "\n" ), '', (string) $submitter['name'] ) . ' <' . $submitter['email'] . '>';
	}
	$answers = '';
	foreach ( (array) ( $fields['interview'] ?? array() ) as $entry ) {
		$answers .= '<p><strong>' . esc_html( $entry['question'] ?? '' ) . '</strong><br>' . nl2br( esc_html( $entry['answer'] ?? '' ) ) . '</p>';
	}
	$body = sprintf(
		'<div style="font-family:Arial,sans-serif;font-size:14px;color:#212529"><p>A graduate sent their story from the Alumni page. It is saved as a <strong>draft</strong>: edit it and press Publish to put it on the website.</p><p><strong>Name:</strong> %s<br><strong>Email:</strong> %s<br><strong>Phone:</strong> %s<br><strong>LinkedIn:</strong> %s<br><strong>Wing:</strong> %s<br><strong>Programme:</strong> %s (%s)<br><strong>Now:</strong> %s<br><strong>Location:</strong> %s</p><p><strong>Headline:</strong> %s</p><div style="white-space:pre-wrap;border-left:3px solid #bd1b21;padding:4px 12px">%s</div>%s<p><a href="%s">Open the draft in WordPress</a>%s</p></div>',
		esc_html( (string) ( $submitter['name'] ?? '' ) ),
		esc_html( (string) ( $submitter['email'] ?? '' ) ),
		esc_html( (string) ( $submitter['phone'] ?? '' ) ),
		esc_html( (string) ( $submitter['linkedin'] ?? '' ) ),
		esc_html( (string) ( $submitter['wing'] ?? '' ) ),
		esc_html( (string) ( $fields['programme'] ?? '' ) ),
		esc_html( (string) ( $fields['graduationYear'] ?? '' ) ),
		esc_html( trim( ( $fields['currentRole'] ?? '' ) . ', ' . ( $fields['company'] ?? '' ), ', ' ) ),
		esc_html( (string) ( $fields['location'] ?? '' ) ),
		esc_html( (string) ( $submitter['headline'] ?? '' ) ),
		esc_html( implode( "\n\n", (array) ( $fields['story'] ?? array() ) ) ),
		$answers,
		esc_url( admin_url( 'post.php?post=' . $post_id . '&action=edit' ) ),
		'' !== ( $fields['photo']['src'] ?? '' ) ? ' (their photo is attached to the draft)' : ''
	);
	wp_mail( $to, 'New alumni story: ' . (string) ( $submitter['name'] ?? '' ), $body, $headers );
}

// "Submitted by" box on stories that came from the form.
