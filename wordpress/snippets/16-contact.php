function nami_msg_statuses() {
	return array(
		'new'     => 'New',
		'replied' => 'Replied',
		'closed'  => 'Closed',
	);
}

function nami_msg_meta( $post_id, $key ) {
	return get_post_meta( $post_id, '_nami_' . $key, true );
}

function nami_msg_settings() {
	$saved = get_option( 'nami_msg_settings', array() );
	$saved = is_array( $saved ) ? $saved : array();
	return array_merge( array( 'to' => 'info@nami.edu.np' ), $saved );
}

function nami_msg_emails( $raw ) {
	$list = preg_split( '/[\s,;]+/', (string) $raw );
	return array_values( array_filter( array_map( 'sanitize_email', $list ), 'is_email' ) );
}

