);

add_action(
	'restrict_manage_posts',
	function ( $post_type ) {
		if ( NAMI_MSG_TYPE !== $post_type ) {
			return;
		}
		$current = isset( $_GET['nami_status'] ) ? sanitize_key( wp_unslash( $_GET['nami_status'] ) ) : '';
		echo '<select name="nami_status"><option value="">All statuses</option>';
		foreach ( nami_msg_statuses() as $value => $label ) {
			printf( '<option value="%s"%s>%s</option>', esc_attr( $value ), selected( $current, $value, false ), esc_html( $label ) );
		}
		echo '</select>';
	}
);

add_action(
	'pre_get_posts',
	function ( $query ) {
		if ( ! is_admin() || ! $query->is_main_query() || NAMI_MSG_TYPE !== $query->get( 'post_type' ) ) {
			return;
		}
		$status = isset( $_GET['nami_status'] ) ? sanitize_key( wp_unslash( $_GET['nami_status'] ) ) : '';
		if ( isset( nami_msg_statuses()[ $status ] ) ) {
			$query->set( 'meta_query', array( array( 'key' => '_nami_status', 'value' => $status ) ) );
		}
	}
);

// Red bubble with the number of new messages next to the menu item.
add_action(
	'admin_menu',
	function () {
		global $menu;
		if ( ! current_user_can( NAMI_MSG_CAP ) || ! is_array( $menu ) ) {
			return;
		}
		$new = new WP_Query(
			array(
				'post_type'      => NAMI_MSG_TYPE,
				'post_status'    => 'publish',
				'meta_key'       => '_nami_status',
				'meta_value'     => 'new',
				'fields'         => 'ids',
				'posts_per_page' => 1,
			)
		);
		if ( $new->found_posts < 1 ) {
			return;
		}
		foreach ( $menu as $index => $item ) {
			if ( 'edit.php?post_type=' . NAMI_MSG_TYPE === ( $item[2] ?? '' ) ) {
				$menu[ $index ][0] .= sprintf( ' <span class="awaiting-mod"><span class="pending-count">%d</span></span>', (int) $new->found_posts );
			}
		}
	},
	99
);

