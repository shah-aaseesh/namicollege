	function () {
		if ( ! current_user_can( 'manage_options' ) ) {
			wp_die( 'You are not allowed to change these settings.', 403 );
		}
		check_admin_referer( 'nami_msg_settings' );
		$to = implode( ', ', nami_msg_emails( wp_unslash( $_POST['to'] ?? '' ) ) );
		update_option( 'nami_msg_settings', array( 'to' => $to ), false );

		$status = 'saved';
		if ( ! empty( $_POST['send_test'] ) ) {
			$recipients                     = nami_msg_emails( $to );
			$GLOBALS['nami_msg_mail_error'] = '';
			$sent                           = ! empty( $recipients ) && wp_mail( $recipients, 'NAMI website: test email', 'This is a test from Contact → Email Settings. If you can read this, contact form alerts will arrive here.' );
			$status                         = $sent ? 'test_ok' : 'test_failed';
			if ( ! $sent ) {
				set_transient( 'nami_msg_test_error_' . get_current_user_id(), empty( $recipients ) ? 'no recipients set' : ( $GLOBALS['nami_msg_mail_error'] ?: 'wp_mail returned false' ), 120 );
			}
		}
		wp_safe_redirect( add_query_arg( array( 'post_type' => NAMI_MSG_TYPE, 'page' => 'nami-msg-settings', 'nami_status' => $status ), admin_url( 'edit.php' ) ) );
		exit;
	}
);

function nami_msg_render_settings() {
	$status = isset( $_GET['nami_status'] ) ? sanitize_key( $_GET['nami_status'] ) : '';
	echo '<div class="wrap"><h1>Message Email Settings</h1>';
	if ( 'saved' === $status ) {
		echo '<div class="notice notice-success is-dismissible"><p>Settings saved.</p></div>';
	} elseif ( 'test_ok' === $status ) {
		echo '<div class="notice notice-success is-dismissible"><p>Settings saved and a test email was sent. Check the inbox (and the spam folder).</p></div>';
	} elseif ( 'test_failed' === $status ) {
		$error = get_transient( 'nami_msg_test_error_' . get_current_user_id() );
		printf( '<div class="notice notice-error"><p>Settings saved, but the test email could not be sent (%s). Install and set up an SMTP plugin such as "WP Mail SMTP", then try again.</p></div>', esc_html( $error ? $error : 'unknown error' ) );
	}
	echo '<form method="post" action="' . esc_url( admin_url( 'admin-post.php' ) ) . '">';
	echo '<input type="hidden" name="action" value="nami_msg_settings">';
	wp_nonce_field( 'nami_msg_settings' );
	printf(
		'<table class="form-table" role="presentation"><tbody><tr><th scope="row"><label for="to">Email new messages to</label></th><td><input type="text" class="large-text" id="to" name="to" value="%s"><p class="description">Separate several addresses with commas. Replying to the alert email answers the sender directly.</p></td></tr></tbody></table>',
		esc_attr( nami_msg_settings()['to'] )
	);
	echo '<p class="submit"><button type="submit" class="button button-primary">Save settings</button> <button type="submit" name="send_test" value="1" class="button">Save and send test email</button></p>';
	echo '</form></div>';
}
