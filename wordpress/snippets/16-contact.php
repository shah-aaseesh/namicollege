add_action(
	'manage_' . NAMI_MSG_TYPE . '_posts_custom_column',
	function ( $column, $post_id ) {
		switch ( $column ) {
			case 'contact':
				$email = (string) nami_msg_meta( $post_id, 'email' );
				echo esc_html( (string) nami_msg_meta( $post_id, 'phone' ) );
				if ( '' !== $email ) {
					echo '<br><a href="mailto:' . esc_attr( $email ) . '">' . esc_html( $email ) . '</a>';
				}
				break;
			case 'excerpt':
				echo esc_html( wp_trim_words( (string) nami_msg_meta( $post_id, 'message' ), 18 ) );
				if ( '' !== (string) nami_msg_meta( $post_id, 'mail_error' ) ) {
					echo '<br><span style="color:#b32d2e">⚠ email alert not sent</span>';
				}
				break;
			case 'status':
				$status = (string) nami_msg_meta( $post_id, 'status' );
				printf( '<strong style="color:%s">%s</strong>', esc_attr( 'new' === $status ? '#bd1b21' : '#50575e' ), esc_html( nami_msg_statuses()[ $status ] ?? $status ) );
				break;
			case 'received':
				echo esc_html( get_the_date( 'j M Y, g:i a', $post_id ) );
				break;
		}
	},
	10,
	2
);

