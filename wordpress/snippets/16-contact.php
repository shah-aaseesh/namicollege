add_action(
	'rest_api_init',
	function () {
		register_rest_route(
			'nami/v1',
			'/messages',
			array(
				'methods'             => 'POST',
				'permission_callback' => function ( WP_REST_Request $request ) {
					if ( ! function_exists( 'nami_cms_settings' ) ) {
						return new WP_Error( 'nami_msg_core_missing', 'The NAMI CMS core snippet is not active.', array( 'status' => 503 ) );
					}
					$secret = (string) nami_cms_settings()['secret'];
					return '' !== $secret && hash_equals( $secret, (string) $request->get_header( 'x-nami-secret' ) );
				},
				'callback'            => 'nami_msg_receive',
			)
		);
	}
);

function nami_msg_receive( WP_REST_Request $request ) {
	$body    = $request->get_json_params();
	$body    = is_array( $body ) ? $body : array();
	$name    = mb_substr( sanitize_text_field( (string) ( $body['name'] ?? '' ) ), 0, 200 );
	$email   = sanitize_email( (string) ( $body['email'] ?? '' ) );
	$phone   = mb_substr( sanitize_text_field( (string) ( $body['phone'] ?? '' ) ), 0, 60 );
	$topic   = mb_substr( sanitize_text_field( (string) ( $body['topic'] ?? '' ) ), 0, 200 );
	$message = mb_substr( sanitize_textarea_field( (string) ( $body['message'] ?? '' ) ), 0, 5000 );
	if ( '' === $name || '' === $message ) {
		return new WP_Error( 'nami_msg_bad_body', 'Invalid message.', array( 'status' => 400 ) );
	}

	$post_id = wp_insert_post(
		array(
			'post_type'   => NAMI_MSG_TYPE,
			'post_status' => 'publish',
			'post_title'  => $name . ' — ' . $topic,
		),
		true
	);
	if ( is_wp_error( $post_id ) ) {
		return new WP_Error( 'nami_msg_store_failed', 'The message could not be stored.', array( 'status' => 500 ) );
	}
	foreach ( array( 'name' => $name, 'email' => $email, 'phone' => $phone, 'topic' => $topic, 'message' => $message, 'status' => 'new' ) as $key => $value ) {
		update_post_meta( $post_id, '_nami_' . $key, wp_slash( $value ) );
	}

	nami_msg_send_email( $post_id );
	return rest_ensure_response( array( 'ok' => true ) );
}

$GLOBALS['nami_msg_mail_error'] = '';
add_action(
	'wp_mail_failed',
	function ( $error ) {
		$GLOBALS['nami_msg_mail_error'] = $error instanceof WP_Error ? $error->get_error_message() : 'unknown error';
	}
);

function nami_msg_send_email( $post_id ) {
	$to = nami_msg_emails( nami_msg_settings()['to'] );
	if ( empty( $to ) ) {
		update_post_meta( $post_id, '_nami_mail_error', 'No recipient set under Contact → Email Settings.' );
		return;
	}
	$name    = (string) nami_msg_meta( $post_id, 'name' );
	$email   = (string) nami_msg_meta( $post_id, 'email' );
	$topic   = (string) nami_msg_meta( $post_id, 'topic' );
	$headers = array( 'Content-Type: text/html; charset=UTF-8' );
	if ( is_email( $email ) ) {
		$headers[] = 'Reply-To: ' . str_replace( array( "\r", "\n" ), '', $name ) . ' <' . $email . '>';
	}
	$body = sprintf(
		'<div style="font-family:Arial,sans-serif;font-size:14px;color:#212529"><p>A new message was sent from the website\'s Contact page.</p><p><strong>From:</strong> %s<br><strong>Email:</strong> %s<br><strong>Phone:</strong> %s<br><strong>Subject:</strong> %s</p><div style="white-space:pre-wrap;border-left:3px solid #bd1b21;padding:4px 12px;margin:12px 0">%s</div><p>Reply to this email to answer %s directly. <a href="%s">Open it in WordPress</a></p></div>',
		esc_html( $name ),
		esc_html( $email ),
		esc_html( (string) nami_msg_meta( $post_id, 'phone' ) ),
		esc_html( $topic ),
		esc_html( (string) nami_msg_meta( $post_id, 'message' ) ),
		esc_html( $name ),
		esc_url( admin_url( 'post.php?post=' . $post_id . '&action=edit' ) )
	);
	$GLOBALS['nami_msg_mail_error'] = '';
	if ( ! wp_mail( $to, 'Website message: ' . $topic . ' — ' . $name, $body, $headers ) ) {
		update_post_meta( $post_id, '_nami_mail_error', wp_slash( $GLOBALS['nami_msg_mail_error'] ?: 'not sent' ) );
	}
}

